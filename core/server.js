/**
 * ตีความคำตอบจากเซิร์ฟเวอร์ — กฎล้วน ไม่แตะเครือข่าย (เทสด้วย node ได้)
 *
 * ── ทำไมต้องมีไฟล์นี้ ───────────────────────────────────────────
 * ระบบนี้มี Apps Script **สองตัว** ที่หน้าตา URL เหมือนกันทุกประการ
 * และทั้งคู่รับคำสั่ง `ping` ได้เหมือนกัน แต่**ชื่อคำสั่งอื่นคนละชุด**
 *
 *   plan  : pullRows  / pushRows   ← ตัวที่แอปนี้ต้องใช้
 *   store : pullTable / pushTable
 *
 * ผลคือถ้าใส่ URL ของ store มา **ปุ่มทดสอบการเชื่อมต่อจะขึ้นว่าผ่าน**
 * แล้วไปพังตอนดึงข้อมูลจริงด้วยข้อความ "ไม่รู้จักคำสั่ง: pullRows"
 * ซึ่งไม่ได้บอกเลยว่าต้องไปแก้อะไร (เจอจริง 10 ต.ค. 2026)
 *
 * แยกออกจากกันได้จากรูปร่างคำตอบของ ping — ดู `identifyScript`
 */

/** `ping` ตอบมาจากสคริปต์ตัวไหน — 'plan' · 'store' · 'unknown'
 *
 *  plan  ตอบ orderCount + recordCount
 *  store ตอบ counts เป็นอ็อบเจกต์ของทุกตาราง
 *  ดูที่ "มีช่องอะไร" ไม่ใช่ "ค่าเป็นเท่าไหร่" — ชีตเปล่าก็ตอบ 0 ได้ทั้งคู่
 */
export function identifyScript(data) {
  if (!data || typeof data !== 'object') return 'unknown';
  if ('orderCount' in data || 'recordCount' in data) return 'plan';
  if (data.counts && typeof data.counts === 'object') return 'store';
  return 'unknown';
}

/** ข้อความอธิบายผลการทดสอบการเชื่อมต่อ — คืน {ok, text}
 *
 *  ต่อกับสคริปต์ผิดตัว = ไม่ผ่าน ไม่ใช่ผ่านแบบมีข้อควรระวัง
 *  เพราะถ้าบอกว่าผ่าน คนจะกดใช้ต่อแล้วไปเจอ error ที่อ่านไม่รู้เรื่องอยู่ดี
 */
export function describePing(data) {
  const kind = identifyScript(data);
  const name = (data && data.spreadsheet) ? ' (ไฟล์ "' + data.spreadsheet + '")' : '';

  if (kind === 'plan') {
    return { ok: true, text: 'เชื่อมต่อได้ปกติ — เป็นสคริปต์ของโปรแกรมแผนงาน' + name };
  }
  if (kind === 'store') {
    return { ok: false, text:
      'ต่อถึงแล้ว แต่เป็นสคริปต์ของ "โปรแกรมสต็อกวัตถุดิบ" ไม่ใช่ของโปรแกรมแผนงาน' + name +
      '\n\nใบส่งของอยู่ในโปรแกรมแผนงาน (plan) ให้ไปเอา URL กับรหัสผ่านจากหน้าตั้งค่าของโปรแกรมนั้นแทน' };
  }
  return { ok: false, text:
    'ต่อถึงแล้ว แต่ไม่แน่ใจว่าเป็นสคริปต์ตัวไหน' + name +
    '\n\nแอปนี้ต้องใช้สคริปต์ของโปรแกรมแผนงาน (plan) ถ้าแน่ใจว่าใส่ถูกแล้ว ' +
    'อาจเป็นเพราะสคริปต์ที่ deploy อยู่เป็นรุ่นเก่ากว่าในโค้ด' };
}

/** แปลข้อความผิดพลาดจากเซิร์ฟเวอร์ให้บอกได้ว่าต้องไปแก้ตรงไหน (INVARIANTS D3)
 *
 *  ข้อความดิบอย่าง "ไม่รู้จักคำสั่ง: pullRows" ถูกต้องในมุมเซิร์ฟเวอร์
 *  แต่คนอ่านแล้วไม่รู้ว่าจะไปทำอะไรต่อ
 */
export function explainError(message) {
  const m = String(message == null ? '' : message);

  if (/ไม่รู้จักคำสั่ง/.test(m)) {
    return m + '\n\nแปลว่า URL นี้ชี้ไปที่สคริปต์คนละตัวกับที่แอปนี้ต้องใช้ ' +
      'เกือบทุกครั้งคือใส่ URL ของโปรแกรมสต็อกวัตถุดิบ (store) มาแทนของโปรแกรมแผนงาน (plan)' +
      '\n\nกด "ตั้งค่าการเชื่อมต่อ" แล้วเอา URL กับรหัสผ่านจากหน้าตั้งค่าของโปรแกรมแผนงานมาใส่';
  }
  if (/ไม่รู้จักตาราง/.test(m)) {
    return m + '\n\nต่อถูกสคริปต์แล้ว แต่สคริปต์ที่ deploy อยู่เป็นรุ่นเก่ากว่าที่แอปนี้ต้องการ ' +
      'ให้เอา google-apps-script.gs รุ่นล่าสุดของโปรแกรมแผนงานไปวางทับ แล้ว Manage deployments → New version';
  }
  if (/token/i.test(m)) {
    return m + '\n\nรหัสผ่านต้องตรงกับค่า TOKEN ที่ตั้งไว้ในสคริปต์ ' +
      'ใช้ตัวเดียวกับที่กรอกในโปรแกรมแผนงาน';
  }
  return m;
}
